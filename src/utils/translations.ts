/**
 * Retorna a tradução para a chave especificada com base no idioma atual
 */
export function translate(language: LanguageOption, key: string, fallback?: string): string {
  const langDict = translations[language] || translations['pt-BR'];
  if (langDict && langDict[key]) {
    return langDict[key];
  }
  const defaultDict = translations['pt-BR'];
  if (defaultDict && defaultDict[key]) {
    return defaultDict[key];
  }
  return fallback || key;
}
